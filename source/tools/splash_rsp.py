"""MIT. Shared helpers for the demo apps' boot splashes (the public RSP1 format of resona/splash.h).

A splash is up to 128 full 320x172 RGB565 frames, each stored as row-major runs of (count, colour), at most
24 KiB in total, played once at power-up for `duration_ms` (frames loop until then). Flat fills and long
horizontal spans are cheap; texture is expensive, so painted art is posterised first.

    frames = [(hold_ms, rgb565_array_172x320), ...]
    data = encode(frames, duration_ms)          # raises if over budget
    write_header(data, 'src/splash_data.h')      # const uint8_t kSplash[] for resona_startup_splash_apply
    preview(decode(data), 'verification/splash.gif')
"""
import struct, zlib
import numpy as np

W, H, MAX_BYTES = 320, 172, 24576


def rgb565(rgb):
    """uint8 HxWx3 -> uint16 HxW"""
    r, g, b = (rgb[..., 0].astype(np.uint16) >> 3), (rgb[..., 1].astype(np.uint16) >> 2), (rgb[..., 2].astype(np.uint16) >> 3)
    return (r << 11) | (g << 5) | b


def rgb888(p):
    p = p.astype(np.uint32)
    return np.stack([(p >> 11) * 255 // 31, ((p >> 5) & 63) * 255 // 63, (p & 31) * 255 // 31], -1).astype(np.uint8)


def runs_of(frame):
    flat = frame.reshape(-1)
    edges = np.flatnonzero(flat[1:] != flat[:-1]) + 1
    starts = np.concatenate([[0], edges]); ends = np.concatenate([edges, [flat.size]])
    return [(int(e - s), int(flat[s])) for s, e in zip(starts, ends)]


def frame_bytes(frame):
    return 8 + 4 * len(runs_of(frame))


def encode(frames, duration_ms):
    if not 1 <= len(frames) <= 128: raise ValueError('1..128 frames')
    payload = bytearray()
    for hold, frame in frames:
        assert frame.shape == (H, W) and frame.dtype == np.uint16
        if not 16 <= hold <= 60000: raise ValueError('hold 16..60000 ms')
        runs = runs_of(frame)
        payload += struct.pack('<II', hold, len(runs))
        for count, colour in runs: payload += struct.pack('<HH', count, colour)
    data = struct.pack('<4s7I', b'RSP1', 32 + len(payload), zlib.crc32(payload) & 0xffffffff, duration_ms, W, H, len(frames), 0) + payload
    if len(data) > MAX_BYTES:
        raise ValueError(f'splash is {len(data)} bytes, over {MAX_BYTES}: ' + ', '.join(str(frame_bytes(f)) for _, f in frames))
    return data


def decode(data):
    assert data[:4] == b'RSP1'
    n, crc, duration, w, h, count, _ = struct.unpack_from('<7I', data, 4)
    assert n == len(data) and crc == zlib.crc32(data[32:]) & 0xffffffff and (w, h) == (W, H)
    off, frames = 32, []
    for _ in range(count):
        hold, nruns = struct.unpack_from('<II', data, off); off += 8
        px = np.empty(W * H, np.uint16); at = 0
        for _ in range(nruns):
            c, col = struct.unpack_from('<HH', data, off); off += 4; px[at:at + c] = col; at += c
        assert at == W * H
        frames.append((hold, px.reshape(H, W)))
    assert off == n
    return frames, duration


def write_header(data, path, name='kSplash'):
    rows = [', '.join(f'0x{b:02x}' for b in data[i:i + 24]) for i in range(0, len(data), 24)]
    with open(path, 'w') as f:
        f.write('// Generated by tools/make_splash.py: the RSP1 boot splash (resona/splash.h), %d bytes. MIT.\n#pragma once\n#include <stdint.h>\n' % len(data))
        f.write('alignas(4) static const uint8_t %s[%d] = {\n %s\n};\n' % (name, len(data), ',\n '.join(rows)))


def preview(decoded, path, scale=2):
    """An animated GIF of what the box plays: the frames with their holds, looped until duration_ms."""
    from PIL import Image
    frames, duration = decoded
    ims, holds, t = [], [], 0
    while True:
        for hold, f in frames:
            if duration and t >= duration: break
            ims.append(Image.fromarray(rgb888(f)).resize((W * scale, H * scale), Image.NEAREST)); holds.append(hold); t += hold
        if not duration or t >= duration or not frames: break
    holds[-1] += 800   # a beat of the last frame before the GIF loops
    ims[0].save(path, save_all=True, append_images=ims[1:], duration=holds, loop=0, optimize=False, disposal=1)


def to_lab(rgb):
    """sRGB (0..255) to CIE Lab, D65."""
    c = rgb.astype(np.float32) / 255
    c = np.where(c > .04045, ((c + .055) / 1.055) ** 2.4, c / 12.92)
    xyz = c @ np.array([[.4124, .2126, .0193], [.3576, .7152, .1192], [.1805, .0722, .9505]], np.float32)
    xyz /= np.array([.95047, 1.0, 1.08883], np.float32)
    f = np.where(xyz > .008856, np.cbrt(xyz), 7.787 * xyz + 16 / 116)
    return np.stack([116 * f[..., 1] - 16, 500 * (f[..., 0] - f[..., 1]), 200 * (f[..., 1] - f[..., 2])], -1)


def posterise(rgb, palette_size=6, keep=None, min_run=3, seed=0):
    """Flatten painted RGB to a few colours with long runs: k-means palette, 3x3 majority smoothing, then short
    horizontal runs merged into their neighbours. `keep` is a list of RGB colours always in the palette."""
    from scipy import ndimage
    px = rgb.reshape(-1, 3).astype(np.float32)
    rng = np.random.default_rng(seed); cent = px[rng.choice(len(px), palette_size, replace=False)]
    if keep: cent[:len(keep)] = np.array(keep, np.float32)
    for _ in range(14):
        lab = ((px[:, None, :] - cent[None]) ** 2).sum(-1).argmin(1)
        for k in range(palette_size):
            if keep and k < len(keep): continue
            m = lab == k
            if m.any(): cent[k] = px[m].mean(0)
    lab = lab.reshape(rgb.shape[:2])
    # majority filter
    votes = np.stack([ndimage.uniform_filter((lab == k).astype(np.float32), 3) for k in range(palette_size)])
    lab = votes.argmax(0)
    # merge short runs per row
    for y in range(lab.shape[0]):
        row = lab[y]; x = 0
        while x < row.size:
            e = x
            while e < row.size and row[e] == row[x]: e += 1
            if e - x < min_run and x > 0: row[x:e] = row[x - 1]
            x = e
    return cent.astype(np.uint8)[lab]
